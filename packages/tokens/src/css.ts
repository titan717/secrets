import {
  breakpoints,
  duration,
  easing,
  elevation,
  fontFamily,
  fontSize,
  fontWeight,
  radius,
  size,
  space,
  zIndex,
} from "./scale";
import {
  accents,
  DEFAULT_ACCENT,
  gradients,
  themeColors,
  deriveAccent,
  type AccentColors,
  type AccentName,
  type ThemeName,
} from "./themes";

export const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/\./g, "_").toLowerCase();
export const colorVarName = (token: string) => `--color-${kebab(token)}`;
export const spaceVarName = (k: string | number) => `--space-${String(k).replace(".", "_")}`;

function block(selector: string, decls: Record<string, string | number>, indent = ""): string {
  const body = Object.entries(decls)
    .map(([k, v]) => `${indent}  ${k}: ${v};`)
    .join("\n");
  return `${indent}${selector} {\n${body}\n${indent}}`;
}

function colorDecls(colors: Record<string, string>): Record<string, string> {
  return Object.fromEntries(Object.entries(colors).map(([k, v]) => [colorVarName(k), v]));
}

function themeDecls(theme: ThemeName): Record<string, string> {
  const shadows = elevation[theme];
  return {
    "color-scheme": theme === "light" ? "light" : "dark",
    ...colorDecls(themeColors(theme, DEFAULT_ACCENT) as unknown as Record<string, string>),
    "--shadow-0": shadows[0],
    "--shadow-1": shadows[1],
    "--shadow-2": shadows[2],
    "--shadow-3": shadows[3],
  };
}

function accentDecls(name: AccentName, theme: ThemeName): Record<string, string> {
  const a: AccentColors = deriveAccent(accents[name].base, theme, accents[name].on);
  return colorDecls(a as unknown as Record<string, string>);
}

function staticDecls(): Record<string, string> {
  const d: Record<string, string> = {};
  for (const [k, v] of Object.entries(space)) d[spaceVarName(k)] = `${v}px`;
  for (const [k, v] of Object.entries(radius)) d[`--radius-${k}`] = `${v}px`;
  d["--font-sans"] = fontFamily.sans;
  d["--font-mono"] = fontFamily.mono;
  for (const [k, v] of Object.entries(fontWeight)) d[`--font-weight-${k}`] = String(v);
  for (const [k, v] of Object.entries(fontSize)) {
    d[`--font-size-${k}`] = `${v.size}px`;
    d[`--line-height-${k}`] = `${v.line}px`;
    d[`--tracking-${k}`] = `${v.tracking}em`;
  }
  for (const [k, v] of Object.entries(duration)) d[`--duration-${k}`] = `${v}ms`;
  for (const [k, v] of Object.entries(easing)) d[`--easing-${k}`] = v;
  for (const [k, v] of Object.entries(zIndex)) d[`--z-${k}`] = String(v);
  for (const [k, v] of Object.entries(size)) d[`--size-${kebab(k)}`] = `${v}px`;
  for (const [k, v] of Object.entries(breakpoints)) d[`--breakpoint-${k}`] = `${v}px`;
  for (const [k, v] of Object.entries(gradients)) d[`--gradient-${k}`] = v;
  d["--focus-ring-width"] = "2px";
  d["--focus-ring-offset"] = "2px";
  return d;
}

const reducedMotion = Object.fromEntries(Object.keys(duration).map((k) => [`--duration-${k}`, "0ms"]));

/**
 * Generate the full tokens.css. Put `data-theme` (and optionally
 * `data-accent`, `data-motion="reduce"`) on <html>.
 */
export function generateCss(): string {
  const out: string[] = [];
  out.push(
    "/* @secrets/tokens — GENERATED by scripts/build-css.ts. Do not edit by hand. */",
    "/* Usage: <html data-theme=\"dark|black|light|system\" data-accent=\"violet|indigo|…\"> */",
    "",
    block(":root", staticDecls()),
    "",
    block(':root, [data-theme="dark"], [data-theme="system"]', themeDecls("dark")),
    "",
    block('[data-theme="black"]', themeDecls("black")),
    "",
    block('[data-theme="light"]', themeDecls("light")),
    "",
    `@media (prefers-color-scheme: light) {\n${block('[data-theme="system"]', themeDecls("light"), "  ")}\n}`,
  );
  for (const name of Object.keys(accents) as AccentName[]) {
    if (name === DEFAULT_ACCENT) continue;
    const a = `[data-accent="${name}"]`;
    out.push(
      "",
      block(`${a}, ${a}[data-theme="dark"], ${a}[data-theme="system"]`, accentDecls(name, "dark")),
      block(`${a}[data-theme="black"]`, accentDecls(name, "black")),
      block(`${a}[data-theme="light"]`, accentDecls(name, "light")),
      `@media (prefers-color-scheme: light) {\n${block(`${a}[data-theme="system"]`, accentDecls(name, "light"), "  ")}\n}`,
    );
  }
  out.push(
    "",
    `@media (prefers-reduced-motion: reduce) {\n${block(":root", reducedMotion, "  ")}\n}`,
    block('[data-motion="reduce"]', reducedMotion),
    "",
  );
  return out.join("\n");
}
